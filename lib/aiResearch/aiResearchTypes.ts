/* =====================================================
AI RESEARCH TYPES
===================================================== */

/*
* The AI Research Agent is an ANALYSIS layer.
*
* It does NOT:
*
* - modify market engines
* - modify Master Score
* - create Rotation-App trading signals
* - execute trades
* - change Rotation-App position sizing
*
* It receives an already calculated market snapshot
* and produces an independent research interpretation.
*
* The snapshot remains the source of truth for the
* quantitative state of the Rotation-App.
*
* IMPORTANT:
*
* Research conclusions such as:
*
* WATCH
* ARMED
* EARLY_STARTER
* CONFIRM
*
* are research interpretations only.
*
* They must never overwrite similarly named execution
* states generated by the Rotation-App itself.
*/

/* =====================================================
GENERIC NUMERIC TYPES
===================================================== */

